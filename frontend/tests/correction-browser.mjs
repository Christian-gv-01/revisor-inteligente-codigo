import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH ? pathToFileURL(process.env.PLAYWRIGHT_MODULE_PATH).href : 'playwright');
process.chdir(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..'));
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
const output = process.argv[2] || 'tmp/correction-browser';
await fs.mkdir(output, { recursive: true });
const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', '5178', '--strictPort'], { cwd: 'frontend', windowsHide: true, stdio: 'ignore' });
for (let attempt = 0; attempt < 60; attempt++) {
  try { if ((await fetch('http://127.0.0.1:5178/')).ok) break; } catch { /* Esperar el servidor local propio. */ }
  await new Promise(resolve => setTimeout(resolve, 100));
}
let browser;
const results = [];
try {
  browser = await chromium.launch({ executablePath: process.env.CODEGUARD_BROWSER_PATH, headless: true });
  const context = await browser.newContext({ acceptDownloads: true, viewport: { width: 1440, height: 1080 } });
  const blocked = [];
  await context.route('**/*', route => {
    const url = new URL(route.request().url());
    if (url.hostname === '127.0.0.1') return route.continue();
    blocked.push(url.origin); return route.abort();
  });
  const page = await context.newPage();
  const downloads = [];
  page.on('download', download => downloads.push(download));
  const open = async (scenario = '') => { await page.goto(`http://127.0.0.1:5178/tests/correction-preview.html${scenario ? '?scenario=' + scenario : ''}`); await page.getByRole('button', { name: 'Previsualizar propuesta', exact: true }).waitFor(); };
  const preview = async () => { await page.getByRole('button', { name: 'Previsualizar propuesta', exact: true }).click(); await page.getByLabel('Código propuesto', { exact: true }).waitFor(); };
  await open(); await preview();
  const original = await page.getByLabel('Código original', { exact: true }).textContent();
  assert(await page.getByRole('button', { name: 'Confirmar y descargar copia', exact: true }).isDisabled());
  assert.equal(downloads.length, 0);
  await page.screenshot({ path: `${output}/previsualizacion-escritorio.png`, fullPage: true });
  results.push({ caso: 'Previsualización sin aprobación no descarga; botón inicialmente bloqueado', aprobado: true });
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Cancelar corrección' }).click();
  await page.getByText('Corrección cancelada.', { exact: false }).waitFor();
  assert.equal(downloads.length, 0);
  assert.equal(await page.locator('#actions').textContent(), '["rechazar"]');
  await preview(); assert(!(await page.getByRole('checkbox').isChecked()));
  results.push({ caso: 'Cancelar rechaza, no descarga y reinicia consentimiento', aprobado: true });
  assert.equal(await page.getByLabel('Código original', { exact: true }).textContent(), original);
  await page.getByRole('checkbox').check();
  const nextDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Confirmar y descargar copia', exact: true }).click();
  const download = await nextDownload;
  assert.equal(download.suggestedFilename(), 'usuarios.corregido.py');
  const contents = await fs.readFile(await download.path(), 'utf8');
  assert(contents.includes('cursor.execute(consulta, (nombre,))'));
  assert.notEqual(contents, original);
  results.push({ caso: 'Confirmar descarga exactamente la propuesta bajo nombre nuevo', aprobado: true });
  await open('changed'); await preview(); await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Confirmar y descargar copia', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'no coincide' }).waitFor();
  assert.equal(downloads.length, 1);
  assert(!(await page.getByRole('checkbox').isChecked()));
  results.push({ caso: 'Respuesta alterada después de aprobar no descarga y revoca consentimiento', aprobado: true });
  await open('slow'); await preview(); await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Confirmar y descargar copia', exact: true }).click();
  await page.getByRole('button', { name: 'Cancelar corrección' }).click();
  await page.waitForTimeout(900);
  assert.equal(downloads.length, 1);
  results.push({ caso: 'Cancelar mientras llega la aprobación impide la descarga tardía', aprobado: true });
  await open('slow'); await preview(); await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Confirmar y descargar copia', exact: true }).click();
  await page.getByRole('button', { name: 'Cambiar entrada de prueba' }).click();
  await page.waitForTimeout(900);
  assert.equal(downloads.length, 1);
  await preview(); assert(!(await page.getByRole('checkbox').isChecked()));
  results.push({ caso: 'Cambiar entrada descarta aprobación anterior y no conserva consentimiento', aprobado: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${output}/previsualizacion-movil.png`, fullPage: true });
  const width = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, viewport: innerWidth }));
  assert(width.scroll <= width.viewport);
  results.push({ caso: 'Previsualización móvil 390 px sin desbordamiento horizontal', aprobado: true });
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.goto('http://127.0.0.1:5178/');
  await page.getByRole('button', { name: 'Probar análisis', exact: true }).click();
  await preview();
  assert(!(await page.getByRole('checkbox').isChecked()));
  await page.screenshot({ path: `${output}/aplicacion-demo.png`, fullPage: true });
  assert.equal(downloads.length, 1);
  results.push({ caso: 'Flujo disponible desde el HomePage real en modo Demo, sin API de correcciones', aprobado: true });
  await fs.writeFile(`${output}/navegador.json`, JSON.stringify({ fecha_utc: new Date().toISOString(), entorno: 'Edge headless local, respuestas simuladas, sin Backend/Gemini/Railway', casos: results, peticiones_externas_bloqueadas: blocked, codigo_ejecutado: false, original_sobrescrito: false }, null, 2) + '\n');
  console.log(JSON.stringify({ aprobados: results.length, externosBloqueados: blocked, output }));
} finally { await browser?.close(); server.kill(); }
